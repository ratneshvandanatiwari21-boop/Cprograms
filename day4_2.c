// /*Relational Opearators: <  >  <=  >=   ==  !=
//  Binary operators
// operator return 0(false) or 1(true) */

    #include<stdio.h>
    int main(){
    int num1 = 25 , num2 = 50;
    printf("<:\t num<num2= %d\n",num1<num2);
    printf(">:\t num>num2= %d\n",num1>num2);
    printf("<=:\t num<=num2= %d\n",num1<=num2);
    printf(">=:\t num>=num2= %d\n",num1>=num2);
    printf("==:\t num==num2= %d\n",num1==num2);
    printf("!=:\t num!=num2= %d\n",num1!=num2);

    return 0;

    }
